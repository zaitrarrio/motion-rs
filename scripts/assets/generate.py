"""Generate crates/motion-core/src/assets/data.rs from the upstream skeleton assets.

Sources (both Apache-2.0):
  * nv-tlabs/kimodo  kimodo/assets/skeletons/{somaskel30,somaskel77,g1skel34,smplx22}
      joints.p, bvh_joints.p, standard_t_pose_global_offsets_rots.p, rest_pose_local_rot.p,
      relaxed_hands_rest_pose.npy
  * NVlabs/motionbricks  tools/onnx/assets/{soma_model_rig,g1_model_rig}.npz (Git LFS)

Usage: python3 -I scripts/assets/generate.py <kimodo repo> <motionbricks rig dir> > crates/motion-core/src/assets/data.rs
"""
import sys, json, subprocess, os
import numpy as np

kimodo, rigs = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))

def pickle_array(path):
    out = subprocess.check_output([sys.executable, "-I", os.path.join(here, "torch_pickle.py"), path])
    d = json.loads(out)
    return np.array(d["data"], dtype=np.float64).reshape(d["shape"])

def emit(name, arr, ty="f32"):
    arr = np.asarray(arr)
    flat = arr.ravel()
    if ty == "f32":
        body = ", ".join(repr(float(np.float32(v))) if np.isfinite(v) else "0.0" for v in flat)
        body = body.replace("inf", "0.0")
        print(f"pub const {name}: [f32; {flat.size}] = [{body}];")
    else:
        body = ", ".join(str(int(v)) for v in flat)
        print(f"pub const {name}: [{ty}; {flat.size}] = [{body}];")
    print(f"pub const {name}_SHAPE: &[usize] = &{list(arr.shape)};")
    print()

print("//! Generated by scripts/assets/generate.py from the nv-tlabs/kimodo and NVlabs/motionbricks")
print("//! skeleton assets (Apache-2.0). Do not edit; regenerate.")
print("#![allow(clippy::all)]")
print()
sk = os.path.join(kimodo, "kimodo/assets/skeletons")
emit("SOMASKEL30_JOINTS", pickle_array(f"{sk}/somaskel30/joints.p"))
emit("SOMASKEL77_JOINTS", pickle_array(f"{sk}/somaskel77/joints.p"))
emit("SOMASKEL77_BVH_JOINTS", pickle_array(f"{sk}/somaskel77/bvh_joints.p"))
emit("SOMASKEL77_STANDARD_TPOSE_GLOBAL_OFFSETS", pickle_array(f"{sk}/somaskel77/standard_t_pose_global_offsets_rots.p"))
emit("SOMASKEL77_RELAXED_HANDS_REST_POSE", np.load(f"{sk}/somaskel77/relaxed_hands_rest_pose.npy"))
emit("G1SKEL34_JOINTS", pickle_array(f"{sk}/g1skel34/joints.p"))
emit("G1SKEL34_REST_POSE_LOCAL_ROT", pickle_array(f"{sk}/g1skel34/rest_pose_local_rot.p"))
emit("SMPLX22_JOINTS", pickle_array(f"{sk}/smplx22/joints.p"))

soma = np.load(os.path.join(rigs, "soma_model_rig.npz"), allow_pickle=False)
emit("MB_SOMA_CAPTURE_OFFSETS", soma["capture_offsets"])
emit("MB_SOMA_STANDARD_OFFSETS", soma["standard_offsets"])
g1 = np.load(os.path.join(rigs, "g1_model_rig.npz"), allow_pickle=False)
emit("MB_G1_MUJOCO_TO_MOTION", g1["mujoco_to_motion_matrix"])
emit("MB_G1_AXES_MUJOCO", g1["mujoco_joint_axis_values_mujoco_space"])
emit("MB_G1_AXES_MOTION", g1["mujoco_joint_axis_values_motion_space"])
emit("MB_G1_ROT_OFFSETS_Q2T", g1["rot_offsets_q2t"])
emit("MB_G1_ROT_OFFSETS_F2Q", g1["rot_offsets_f2q"])
emit("MB_G1_CAPTURE_NEUTRAL_JOINTS_MUJOCO", g1["capture_neutral_joints_mujoco"])
emit("MB_G1_NEUTRAL_JOINTS", g1["neutral_joints"])
emit("MB_G1_MUJOCO_PARENTS", g1["mujoco_joint_including_root_parent_list"], "i32")
emit("MB_G1_JOINT_PARENTS", g1["joint_parents"], "i32")
emit("MB_G1_MOTION_TO_MUJOCO", g1["motion_indices_to_mujoco_indices"], "i32")
emit("MB_G1_MUJOCO_TO_MOTION_INDICES", g1["mujoco_indices_to_motion_indices"], "i32")
